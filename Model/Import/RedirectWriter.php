declare(strict_types=1);

namespace Softaware\Blog\Model\Import;

use Magento\Framework\App\Route\ConfigInterface as RouteConfig;
use Magento\UrlRewrite\Model\ResourceModel\UrlRewrite as UrlRewriteResource;
use Magento\UrlRewrite\Model\UrlFinderInterface;
use Magento\UrlRewrite\Model\UrlRewriteFactory;
use Magento\UrlRewrite\Service\V1\Data\UrlRewrite;

/**
 * 301 redirects from old WordPress addresses, stored as custom URL rewrites (Marketing > SEO & Search >
 * URL Rewrites, where they can be edited or removed).
 *
 * A redirect is never created over an existing URL rewrite, for an address that starts with one of the store's
 * own routes (checkout, customer, ...) or for an address that equals its target.
 */
class RedirectWriter
{
    public const CREATED = 'created';
    public const EXISTS = 'exists';
    public const SKIPPED = 'skipped';

    private const RESERVED = ['admin', 'media', 'static', 'pub', 'errors', 'setup', 'rest', 'soap', 'graphql', 'index.php'];

    public function __construct(
        private readonly UrlFinderInterface $urlFinder,
        private readonly UrlRewriteFactory $urlRewriteFactory,
        private readonly UrlRewriteResource $urlRewriteResource,
        private readonly RouteConfig $routeConfig
    ) {
    }

    public function add(string $requestPath, string $targetPath, int $storeId, string $description): string
    {
        $requestPath = ltrim($requestPath, '/');
        $targetPath = ltrim($targetPath, '/');
        if ($requestPath === '' || $requestPath === $targetPath || $this->isReserved($requestPath)) {
            return self::SKIPPED;
        }
        $existing = $this->urlFinder->findOneByData([
            UrlRewrite::REQUEST_PATH => $requestPath,
            UrlRewrite::STORE_ID => $storeId,
        ]);
        if ($existing !== null) {
            return self::EXISTS;
        }
        $rewrite = $this->urlRewriteFactory->create();
        $rewrite->setData([
            UrlRewrite::ENTITY_TYPE => 'custom',
            UrlRewrite::ENTITY_ID => 0,
            UrlRewrite::REQUEST_PATH => $requestPath,
            UrlRewrite::TARGET_PATH => $targetPath,
            UrlRewrite::REDIRECT_TYPE => 301,
            UrlRewrite::STORE_ID => $storeId,
            UrlRewrite::DESCRIPTION => mb_substr($description, 0, 255),
            UrlRewrite::IS_AUTOGENERATED => 0,
        ]);
        $this->urlRewriteResource->save($rewrite);
        return self::CREATED;
    }

    public function isReserved(string $requestPath): bool
    {
        $first = strtolower(explode('/', ltrim($requestPath, '/'))[0]);
        if ($first === '' || in_array($first, self::RESERVED, true)) {
            return true;
        }
        return (bool)$this->routeConfig->getRouteByFrontName($first, 'frontend');
    }
}
